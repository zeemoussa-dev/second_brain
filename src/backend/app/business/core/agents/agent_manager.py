    def regenerate_specialists_section(self, agent_id: str) -> Agent | None:
        """Explicit, separate call -- NEVER triggered automatically inside
        create/update (operator: "since we will be changing depends_on
        sometimes, specially when we are customizing" -- too disruptive
        to rewrite a parent's real prompt on every tweak).

        `depends_on` has no real Hermes backing (confirmed against the
        real `hermes peer --help` -- that's cross-gateway only); every
        real same-install relay this session hand-built works because a
        `terminal(hermes -p <profile> chat ...)` instruction was
        hand-written into the PARENT's own SOUL.md. This generates that
        instruction instead of relying on it being written by hand.

        Real, confirmed direction (live data, not assumed): the CHILD's
        `depends_on` points at the PARENT
        (`compass-pricing-expert.depends_on == ['compass-expert']`), but
        the relay text belongs on the PARENT's SOUL.md -- so this finds
        every agent whose `depends_on` includes `agent_id` (this agent's
        real "specialists"), not the other way around.

        Idempotent -- the generated block is wrapped in
        `_SPECIALISTS_BEGIN`/`_SPECIALISTS_END` markers so a re-run
        replaces its own prior block instead of duplicating it, and a
        parent left with zero real children has the block removed
        entirely rather than left stale."""
        agent = self.get_by_id(agent_id)
        if agent is None:
            return None
        children = sorted(
            (a for a in self.get_all() if agent_id in a.depends_on), key=lambda a: a.id,
        )
        current_prompt = agent.prompt or f"You are {agent.name}."
        new_prompt = self._apply_specialists_block(current_prompt, children)
        if new_prompt == current_prompt:
            return agent
        return self.update(agent_id, prompt=new_prompt)

    def _specialists_block_text(self, children: list[Agent]) -> str | None:
        if not children:
            return None
        bullets = "\n".join(
            f"- **`{child.id}`** -- {child.description or child.name}" for child in children
        )
        return (
            f"{_SPECIALISTS_BEGIN}\n"
            "## Your own specialists\n\n"
            "Each is a separate Hermes profile -- reach one with:\n\n"
            "```\n"
            'terminal(command="hermes -p <profile> chat -q \\"<the real question, in your own words>\\" '
            '-Q --create-if-missing -c \\"<a session name for this thread>\\"")\n'
            "```\n\n"
            "Reuse the same `-c` session name across a multi-turn exchange so context carries over. "
            "Report their reply back in your own words -- don't paste raw output.\n\n"
            f"{bullets}\n"
            f"{_SPECIALISTS_END}"
        )

    def _apply_specialists_block(self, prompt: str, children: list[Agent]) -> str:
        block = self._specialists_block_text(children)
        start = prompt.find(_SPECIALISTS_BEGIN)
        end = prompt.find(_SPECIALISTS_END)
        has_existing_block = start != -1 and end != -1
        if has_existing_block:
            end += len(_SPECIALISTS_END)
            before, after = prompt[:start].rstrip(), prompt[end:].lstrip()
            if block is None:
                # No real children left -- remove the block entirely
                # rather than leaving a stale one behind.
                return f"{before}\n\n{after}".strip() if after else before
            return f"{before}\n\n{block}\n\n{after}".strip() if after else f"{before}\n\n{block}"
        if block is None:
            return prompt
        return f"{prompt.rstrip()}\n\n{block}"

