"""AgentManager -- the ONLY door onto Agent data (mirrors SectionManager's
own "one real gateway" rule). Composes a real Agent from several genuinely
separate real sources -- there is no single owning file the way
section_registry.py was for Section:

- Hermes itself (`HermesProfiles`, app/hermes/profiles.py) -- name/
  description/model/reasoning_effort/skills/the real SOUL.md text. This
  is Hermes' own data; Second Brain never fabricates it.
- The Registry (`data_access/registry/loader.py`, REQ-SB-80) --
  section_id/type/is_background_agent/depends_on, once an agent has been
  migrated into the data/ tree. Falls through to the same worker/Data
  Gatherer/no-deps/not-background defaults agents_map_adapter.py's old
  hardcoded dicts always used, for an agent not yet migrated.
- `agent_visual_registry.py` -- icon/color overrides. Deliberately NOT
  folded in here yet (operator: "Agents will have more than one file") --
  this Manager composes it, same as agents_map_adapter.py already does,
  rather than absorbing it.

Fields with no real backing store yet (`working_mode` beyond the single
"autonomous" default) are left at an honest, undecorated default rather
than fabricated -- same discipline agents_map_adapter.py's own module
docstring already committed to.

Write side (create/update/delete): real Hermes-side operations
(`HermesClient.create_profile`/`delete_profile`/`describe_profile`,
`HermesProfiles.update`/`write_soul`) already existed as library
primitives -- unused anywhere until now. The ONE genuinely new piece is
the Registry-side `Agent.json`/`soul.md` writer -- nothing in the app
ever wrote these before (the loader only ever read them; the only prior
writer was a one-off migration script), so `_write_registry_agent`
below is new, not a migration of existing logic the way
section_manager.py's writers were. `Agent.json` is ONE file (2026-08-28,
operator: "we should have one Json file describing the Agent") --
id/name/type/is_background_agent/depends_on/provider_id/skill_ids plus
icon/color, no separate Agent-visual.json anymore; `agent_visual_registry.py`'s
own Registry-mirror write updates the same file's icon/color keys in
place instead of writing a second file. The Registry's own lowercase
`soul.md` has no real reader anywhere (grepped before writing this) --
it exists purely because loader.py's own _load_one_agent is fail-loud on
a missing/empty one, so this Manager treats it as a one-way pushed
MIRROR of the real Hermes SOUL.md (same shape as section_manager.py's
own Section.json mirror), never a second source of truth.
`prompt`+`guardrails`+`scope` compose into that ONE real SOUL.md write
(`_soul_text`) -- confirmed by the operator: both guardrails and scope
get woven into the real SOUL.md text, not stored as separate Hermes-side
fields.

Raw I/O (2026-08-28 layering correction, operator: "Managers understand
Entities, Data Access understands stores... I/O always happens in Data
Access") lives in `data_access/registry/writer.py` (Agent.json/soul.md
writes, folder deletes -- shared with SectionManager since both write
into the same Registry tree) -- this file holds zero raw file calls,
only entity-shaping and orchestrating the real Hermes-side calls.
"""
